-- Session table to to bind a session id and the logged user  
CREATE TABLE meeting
(
  	  id 		 		SERIAL	NOT NULL 	-- the primary key automatically generated by a sequence
  	, tourney_id 	 	integer NOT NULL 	-- the foreign key toward the TOURNEY table
  	, round_id 	 		integer				-- the ROUND identifier
  	, playoff_id 	 	integer				-- the PLAYOFF identifier
  	, eliminatory_id 	integer				-- the ELIMINATORY identifier
	, json 				varchar 			-- the JSON string representing the meeting
);
