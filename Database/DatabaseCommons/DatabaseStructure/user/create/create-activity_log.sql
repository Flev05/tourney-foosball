CREATE TABLE activity_log
(
  	  id SERIAL 		NOT NULL		-- the primary key automatically generated by a sequence
  	, creation_date 	timestamp NOT NULL
  	, statement 		character varying(4096) NOT NULL
  	, type 				character varying(64) 
  	, user_id			integer			-- the user id the person belongs to
);
