CREATE TABLE client
(
  	  id 					SERIAL NOT NULL 			-- the primary key automatically generated by a sequence
  	  
	, firstname			character varying(64) 			-- the client fistname
	, lastname			character varying(64) 			-- the client lastname
	, business_name		character varying(128) 			-- the the business name of the client if any

	, address			character varying(256) NOT NULL	-- the client address
	, phone_number		character varying(32)  NOT NULL	-- the client phone number
	, email 			character varying(256) NOT NULL -- the client email
	
	, site_url			character varying(1024)  		-- the the client site URL

  	, location_id		integer NOT NULL
);
  
  