-- table
CREATE TABLE company
(
  	  id 					SERIAL NOT NULL 				-- the primary key automatically generated by a sequence
  	  
	, company_code 			character varying(64)  NOT NULL -- the COMPANY CODE
	, name 					character varying(256) NOT NULL -- the COMPANY name
	, address				character varying(256) NOT NULL	-- the COMPANY address
	, phone_number			character varying(32)  NOT NULL	-- the COMPANY phone number
	
	, vat					character varying(32)  NOT NULL -- the COMPANY VAT (Value Added Tax)
	, tax_code				character varying(32)  			-- the COMPANY tax code
	, logo_url				character varying(1024)  		-- the COMPANY LOGO URL address

	, company_email 		character varying(256) NOT NULL
	, mail_server_host 		character varying(128)
	, mail_server_port 		integer
	, mail_server_password 	character varying(128)
	, mail_protocol 		character varying(32)
	, company_condition 	text
	, mail_server_username 	character varying(64)
	, revalidation_cost 	float
	, ipg_id 				integer
);
  
  