	, phone_number	character varying(32)  	NOT NULL	-- the IPG phone number
	, tax_code		character varying(32)  				-- the IPG tax code
	, site			character varying(1024)  			-- the IPG LOGO URL address
	, email 		character varying(256) NOT NULL
);
  
  