CREATE TABLE location
(
  	    id SERIAL 		NOT NULL  				-- the primary key automatically generated by a sequence
	  , city 			character varying(50)	-- the name of the of the city: MILANO, LEGNANO, PREGNANA MILANESE, CAPOSELE,...
	  , city_code 		character(4)			-- the city code: F205, H427, B674, ...
	  , province_code 	character(2)			-- the full province name: MI, CR, VA, ...
	  , zip_code 		character(5)			-- 5 numeric chars for the ZIP code: 20010, 83040, 00600,...
	  , country_code 	character(2)			-- the country code: IT, FR, DE, ES,...
);

