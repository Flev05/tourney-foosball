CREATE TABLE person
(
  	  id SERIAL 		NOT NULL		-- the primary key automatically generated by a sequence
  	, first_name 		character varying(50) NOT NULL
  	, last_name 		character varying(50) NOT NULL
  	, residence_address character varying(100) 
  	, user_id			integer			-- the user id the person belongs to
);
