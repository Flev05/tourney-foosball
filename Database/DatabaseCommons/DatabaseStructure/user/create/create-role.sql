-- GUI configuration table to configure the optiona columns in the presence table.  
-- Example are: extratime, studio, dayoff, ....  
CREATE TABLE role
(
  	  id 			SERIAL	NOT NULL 		-- the primary key automatically generated by a sequence
   	, role_type_id 	integer NOT NULL		-- reference to ROLE_TYPE table
  	, company_id 	integer NOT NULL		-- reference to COMPANY table
  	, name character varying(50) NOT NULL
  	, description 	character varying(1024)	-- a brief desctiption of the object under configuration
);
