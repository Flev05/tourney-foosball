-- Session table to to bind a session id and the logged user  
CREATE TABLE session
(
  	 id 		 	SERIAL	NOT NULL 		-- the primary key automatically generated by a sequence
  	, user_id 	 	integer					-- the foreign key toward the USER table
	, session_id 	character varying(64)	-- the user session id, the cokie value in session
	, creation_date timestamp without time zone NOT NULL
	, user_info 	character varying(1000)	-- the user info took from the http clien connection
);
