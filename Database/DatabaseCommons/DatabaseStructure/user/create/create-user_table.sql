-- GUI configuration table to configure the optiona columns in the presence table.  
-- Example are: extratime, studio, dayoff, ....  
CREATE TABLE user_table
(
  	 id 			SERIAL	NOT NULL 				-- the primary key automatically generated by a sequence
  	, username 		character varying(30) NOT NULL 	-- the unique user name of the user
  	, password 		character varying(64) DEFAULT 	'D41D8CD98F00B204E9800998ECF8427E'::character varying 	-- the empty password associated to he user
  	, gecos 		character varying(2048) DEFAULT ''::character varying
	, person_id 	integer							-- the foreign key toward the PERSON table
	, role_admin 	boolean							-- true the user admins the role, false don't
	, guide			text
);
