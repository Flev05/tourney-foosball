-- Session table to to bind a session id and the logged user  
CREATE TABLE player
(
  	  id 		 	SERIAL	NOT NULL 	-- the primary key automatically generated by a sequence
	, player_name	character varying(256)	NOT NULL	-- the the name in clear of the player
  	, client_id 	integer  			-- the foreign key toward the CLIENT table
  	, session_id	integer 			-- the foreign key toward the SESSION table
  	, country_id	integer 			-- the foreign key toward the COUNTRY table
	, json 			varchar 			-- the JSON string representing the meeting
);
